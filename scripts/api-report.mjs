#!/usr/bin/env node
/**
 * Public API report, generated with the TypeScript 7 native API.
 *
 * Uses the new "Corsa" surface (`typescript/unstable/sync`): open the project,
 * take a snapshot, then read the entry program through the checker and the
 * emitter. No legacy compiler API involved.
 *
 *   node scripts/api-report.mjs           # write api-report.md
 *   node scripts/api-report.mjs --check   # fail if api-report.md is stale
 *
 * The emitter inherits line endings from the source files it last read, so the
 * output must be normalized before it is compared or written: otherwise the
 * report flips between LF and CRLF depending on the platform and on the order
 * in which files were loaded, and `--check` fails on a clean checkout.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { API, SignatureKind } from "typescript/unstable/sync";
import { SyntaxKind } from "typescript/unstable/ast";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const config = join(root, "tsconfig.build.json");
const entry = join(root, "src", "index.ts");
const output = join(root, "api-report.md");

const api = new API();

/** One line ending for every platform: the report is compared byte for byte. */
function toLf(text) {
  return text.replace(/\r\n?/g, "\n");
}

function signatureOf(checker, emitter, node, symbol) {
  const type = checker.getTypeOfSymbol(symbol);
  const [signature] = checker.getSignaturesOfType(type, SignatureKind.Call);
  if (!signature) return null;
  const declaration = checker.signatureToSignatureDeclaration(
    signature,
    SyntaxKind.FunctionType,
    node,
    0,
  );
  return declaration ? toLf(emitter.printNode(declaration)) : null;
}

function nameOf(node) {
  return node.name?.text ?? null;
}

function collect(program, checker, emitter) {
  const source = program.getSourceFile(entry);
  if (!source) throw new Error(`entry not found in program: ${entry}`);

  const blocks = [];

  for (const statement of source.statements) {
    const exported = (statement.modifiers ?? []).some(
      (modifier) => modifier.kind === SyntaxKind.ExportKeyword,
    );

    switch (statement.kind) {
      case SyntaxKind.InterfaceDeclaration:
      case SyntaxKind.TypeAliasDeclaration: {
        if (!exported) break;
        blocks.push(toLf(emitter.printNode(statement)));
        break;
      }
      case SyntaxKind.FunctionDeclaration: {
        if (!exported) break;
        const name = nameOf(statement);
        if (!name) break;
        const symbol = checker.getSymbolAtLocation(statement.name);
        if (!symbol) break;
        const signature = signatureOf(checker, emitter, statement, symbol);
        if (signature) {
          const arrow = signature.lastIndexOf("=>");
          const parameters = signature.slice(0, arrow).trim();
          const returns = signature.slice(arrow + 2).trim();
          blocks.push(`declare function ${name}${parameters}: ${returns};`);
        }
        break;
      }
      case SyntaxKind.ExportDeclaration: {
        blocks.push(toLf(emitter.printNode(statement)).replace(/;$/, ";"));
        break;
      }
      default:
        break;
    }
  }

  return blocks;
}

function render(blocks) {
  return [
    "# Public API",
    "",
    "<!-- Generated by scripts/api-report.mjs with the TypeScript 7 native API. -->",
    "<!-- Run `npm run api-report` to update, `npm run api-report:check` to verify. -->",
    "",
    ...blocks.flatMap((block) => ["```ts", block.trim(), "```", ""]),
  ].join("\n");
}

try {
  const snapshot = api.updateSnapshot({ openProjects: [config] });
  const project = snapshot.getProject(config) ?? snapshot.getProjects()[0];
  if (!project) throw new Error("no project loaded");

  const report = render(collect(project.program, project.checker, project.emitter));
  const check = process.argv.includes("--check");

  if (check) {
    const current = toLf(await readFile(output, "utf8").catch(() => ""));
    if (current.trim() !== report.trim()) {
      console.error("api-report.md is out of date. Run `npm run api-report`.");
      process.exitCode = 1;
    } else {
      console.log("api-report.md is up to date.");
    }
  } else {
    await writeFile(output, report);
    console.log(`wrote ${output}`);
  }
} finally {
  api.close();
}
